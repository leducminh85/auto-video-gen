const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const { createStore } = require('./projectStore.cjs');
(async () => {
  const store = createStore(path.resolve('public'));
  const original = store.list();
  assert.ok(original.length, 'A demo project is required');
  const originalData = store.read(original[0].id);
  const fixture = structuredClone(originalData);
  fixture.metadata.title = 'Project route test';
  const created = store.create(fixture);
  const id = created.metadata.project_id;
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://localhost:3000/');
    await page.getByRole('heading', { name: 'Dự án của bạn' }).waitFor();
    await page.getByRole('heading', { name: 'Project route test', exact: true }).click();
    await page.waitForURL(`**/project/${id}`);
    await page.getByRole('heading', { name: 'Wevic Video Studio' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Tạo video mới', exact: true }).count(), 0);
    await page.reload();
    await page.getByRole('heading', { name: 'Wevic Video Studio' }).waitFor();
    const edit = store.read(id); edit.metadata.title = 'Project route test edited';
    const saved = await page.request.post(`http://localhost:3000/api/projects/${id}`, { data: edit });
    assert.equal(saved.status(), 200);
    assert.deepEqual(store.read(original[0].id), originalData);
    const tiny = structuredClone(edit);
    Object.assign(tiny.metadata, { width: 320, height: 180 });
    tiny.scenes = tiny.scenes.slice(0, 1);
    tiny.scenes[0].duration_in_frames = 6;
    tiny.scenes[0].beats = tiny.scenes[0].beats.slice(0, 1);
    tiny.scenes[0].beats[0].duration_in_frames = 6;
    const render = await page.request.post(`http://localhost:3000/api/projects/${id}/render`, { data: tiny });
    assert.equal(render.status(), 200, await render.text());
    const video = await page.request.get(`http://localhost:3000/projects/${id}/final-video.mp4`);
    assert.match(video.headers()['content-type'], /video\/mp4/);
    assert.deepEqual(await video.body(), fs.readFileSync(path.join('public/projects', id, 'final-video.mp4')));
    const partial = await page.request.get(`http://localhost:3000/projects/${id}/final-video.mp4`, { headers: { Range: 'bytes=0-99' } });
    assert.equal(partial.status(), 206);
    assert.equal((await partial.body()).length, 100);
    assert.deepEqual(store.read(original[0].id), originalData);

    await page.getByRole('link', { name: 'Dự án', exact: true }).click();
    await page.getByRole('link', { name: 'Tạo project mới' }).click();
    await page.waitForURL('**/project/new');
    await page.getByRole('textbox', { name: 'Tên video', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Đóng trình tạo video' }).click();
    await page.waitForURL('http://localhost:3000/');
    await page.locator('.project-card').filter({ hasText: 'Project route test edited' }).hover();
    await page.getByLabel('Tùy chọn Project route test edited', { exact: true }).click();
    await page.getByRole('button', { name: 'Xóa dự án', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('button', { name: 'Hủy', exact: true }).click();
    assert.ok(store.read(id));
    await page.locator('.project-card').filter({ hasText: 'Project route test edited' }).hover();
    await page.getByLabel('Tùy chọn Project route test edited', { exact: true }).click();
    await page.getByRole('button', { name: 'Xóa dự án', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Xóa dự án', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'detached' });
    assert.throws(() => store.read(id), /Không tìm thấy/);
    assert.equal((await page.request.get(`http://localhost:3000/api/projects/${id}`)).status(), 404);
    await page.goto(`http://localhost:3000/project/${id}`);
    await page.getByRole('alert').filter({ hasText: 'Không đọc được dự án' }).waitFor();
    await page.goto('http://localhost:3000/');
    await page.getByRole('heading', { name: 'Dự án của bạn' }).waitFor();
    fs.mkdirSync('reports', { recursive: true });
    await page.screenshot({ path: 'reports/project-dashboard-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: 'reports/project-dashboard-mobile.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS: live localhost:3000 dashboard, project deep-link/reload, scoped save/render/MP4 download, new page, delete cancel/confirm, 404 and mobile layout');
  } finally {
    await browser.close();
    try { store.remove(id); } catch {}
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
