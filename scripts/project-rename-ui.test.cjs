const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require('playwright');
const { createStore } = require('./projectStore.cjs');
(async () => {
  const store = createStore(path.resolve('public'));
  const source = store.read(store.list()[0].id);
  source.metadata.title = 'Rename UI test';
  const project = store.create(source);
  const id = project.metadata.project_id;
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const base = 'http://localhost:3000';
    await page.goto(base);
    const card = page.locator('.project-card').filter({ has: page.getByRole('heading', { name: 'Rename UI test', exact: true }) });
    await card.waitFor();
    const menu = card.locator('summary');
    await page.mouse.move(0, 0);
    assert.equal(await menu.evaluate(el => getComputedStyle(el).opacity), '0');
    await card.hover();
    await menu.click();
    await page.getByRole('button', { name: 'Đổi tên', exact: true }).click();
    await page.getByRole('textbox', { name: 'Tên dự án', exact: true }).fill('');
    assert.equal(await page.getByRole('button', { name: 'Lưu tên' }).isDisabled(), true);
    await page.getByRole('textbox', { name: 'Tên dự án', exact: true }).fill('Video đã đổi tên');
    await page.getByRole('button', { name: 'Lưu tên' }).click();
    await page.getByRole('dialog').waitFor({ state: 'detached' });
    await page.getByRole('heading', { name: 'Video đã đổi tên', exact: true }).waitFor();
    await page.reload();
    await page.getByRole('heading', { name: 'Video đã đổi tên', exact: true }).waitFor();
    const saved = store.read(id);
    assert.equal(saved.metadata.title, 'Video đã đổi tên');
    assert.equal(saved.metadata.render_dirty, project.metadata.render_dirty);
    assert.deepEqual(saved.scenes, project.scenes);
    await page.getByRole('heading', { name: 'Video đã đổi tên', exact: true }).click();
    await page.getByRole('heading', { name: 'Xem trước', exact: true }).waitFor();
    assert.equal(await page.locator('.studio-identity p').innerText(), 'Video đã đổi tên');
    const alignment = await page.locator('.timeline-tools').evaluate(el => {
      const box = el.getBoundingClientRect(), zoom = el.querySelector('.timeline-zoom').getBoundingClientRect();
      return box.right - zoom.right;
    });
    assert.ok(alignment <= 20, `Zoom right gap: ${alignment}`);
    await page.goto(base);
    await page.getByLabel('Tùy chọn Video đã đổi tên', { exact: true }).focus();
    assert.equal(await page.getByLabel('Tùy chọn Video đã đổi tên', { exact: true }).evaluate(el => getComputedStyle(el).pointerEvents), 'auto');
    await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Đổi tên', exact: true }).click();
    await page.getByRole('textbox', { name: 'Tên dự án', exact: true }).fill('Hủy đổi tên');
    await page.getByRole('button', { name: 'Hủy', exact: true }).click();
    assert.equal(store.read(id).metadata.title, 'Video đã đổi tên');
    await page.goto(base);
    await page.getByRole('heading', { name: 'Video đã đổi tên', exact: true }).waitFor();
    await page.screenshot({ path: 'reports/project-listing-refined.png', fullPage: true });
    const touch = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    const mobile = await touch.newPage();
    await mobile.goto(base);
    const touchMenu = mobile.getByLabel('Tùy chọn Video đã đổi tên', { exact: true });
    await touchMenu.waitFor();
    assert.equal(await touchMenu.evaluate(el => getComputedStyle(el).opacity), '1');
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await mobile.screenshot({ path: 'reports/project-listing-refined-mobile.png', fullPage: true });
    console.log('PASS: real rename persistence, editor title, cancel, blank validation, unchanged timeline/render state, hover/keyboard/touch menu, zoom alignment.');
  } finally { await browser.close(); store.remove(id); }
})().catch(e => { console.error(e); process.exitCode = 1; });
